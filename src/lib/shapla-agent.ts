/* ---------- formatting ---------- */

export function money(v: number) {
  const a = Math.abs(v);
  if (a >= 1e7) return `৳ ${(a / 1e7).toFixed(2)} Cr`;
  if (a >= 1e5) return `৳ ${(a / 1e5).toFixed(1)} L`;
  return `৳ ${Math.round(a).toLocaleString("en-IN")}`;
}
const num = (v: number) => Math.round(v).toLocaleString("en-IN");
const pct = (v: number, d = 1) => `${Math.abs(v).toFixed(d)}%`;
const day = (iso: string) => new Date(`${iso}T00:00:00`).toLocaleDateString("en-GB", { day: "numeric", month: "short" });
const dayYear = (iso: string) => new Date(`${iso}T00:00:00`).toLocaleDateString("en-GB", { day: "numeric", month: "short", year: "numeric" });
const sum = (a: readonly number[]) => a.reduce((s, x) => s + x, 0);
const by = <T,>(xs: T[], f: (x: T) => number) => [...xs].sort((a, b) => f(b) - f(a));
const up = (now: number, before: number) => (before ? `${now >= before ? "up" : "down"} ${pct(((now - before) / before) * 100)}` : "");

