const norm = (s: string) => s.toLowerCase().replace(/[^a-z0-9ঀ-৿&]+/g, " ").replace(/\s+/g, " ").trim();

/** Finds a named product, customer, employee, supplier or region in the question. */
function findNamed(q: string): Reply | null {
  const n = ` ${norm(q)} `;
  const hit = (name: string) => n.includes(` ${norm(name)} `);
  const e = S.employees.find((x) => hit(x.name));
  if (e) return employeeProfile(e.id);
  const c = S.customers.find((x) => hit(x.name));
  if (c) return customerProfile(c.id);
  const s = S.suppliers.find((x) => hit(x.name) || hit(x.name.split(" ").slice(0, 2).join(" ")));
  if (s) return supplierProfile(s.id);
  // products: best match on the name without "Shapla", preferring the longest name
  const ps = by(S.products.filter((p) => hit(p.name.replace(/^Shapla /, ""))), (p) => p.name.length);
  if (ps.length) {
    const sku = ps[0].sku;
    return /(goes into|made of|ingredient|recipe|bom|bill of material|material)/.test(n) ? bomFor(sku) : productProfile(sku);
  }
  const r = S.regions.find((x) => hit(x.name) && /region|division/.test(n));
  if (r) return regionProfile(r.id);
  return null;
}

